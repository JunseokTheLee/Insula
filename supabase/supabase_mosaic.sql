-- Run this once in the Supabase SQL editor (Project → SQL Editor → New query).
-- Photomosaic feature (weavo.html): admins create a low-res reference image
-- as a grid of target colors; signed-in users upload artwork whose average
-- color gets matched to the closest still-open grid cell, gradually
-- reassembling the reference image out of user submissions.

-- ── 1. Admin flag on profiles ────────────────────────────────────────────
-- SECURITY: profiles currently grants blanket insert/update to `authenticated`
-- with no column restriction, so without locking this down, any signed-in
-- user could run sb.from('profiles').update({ is_admin: true }) and
-- self-promote. Replace the blanket grant with a column-scoped one that
-- excludes is_admin (and id/created_at/updated_at, which are never
-- client-set today).
alter table public.profiles
  add column if not exists is_admin boolean not null default false;

revoke insert, update on public.profiles from authenticated;

grant insert (id, name, avatar_url, username, bio, disabilities, links, country_id, city)
  on public.profiles to authenticated;
grant update (name, avatar_url, username, bio, disabilities, links, country_id, city)
  on public.profiles to authenticated;

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- After running this file, manually promote your own account in the SQL
-- editor (which runs as postgres and bypasses RLS/grants):
